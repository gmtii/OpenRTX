"""
Turn the TETRA call tones, WAV files, into openrtx/src/protocols/TETRA/
TetraTones.c: 8 kHz mono 16-bit samples, as the TETRA speech playback
plays them, peak normalised, with the silence at both ends cut.

  snd_call_setup.wav     a call set up
  snd_call_released.wav  the call released
  snd_priotity.wav       a priority or emergency call set up
  snd_roaming.wav        the roaming tuned another cell

Any rate, mono or stereo (the left channel), 16-bit PCM.

Example:
  python3 scripts/c62/tetra_tones.py ~/c62/tonos
"""

import argparse
import os
import struct
import wave

RATE = 8000
PEAK = 4000       # A third of the first level, under the speech: -18 dBFS
SILENCE = 200     # Samples under this at the ends are cut
TONES = [
    ("setup", "snd_call_setup.wav"),
    ("released", "snd_call_released.wav"),
    ("priority", "snd_priotity.wav"),
    ("roaming", "snd_roaming.wav"),
]


def read(path):
    w = wave.open(path)
    ch, width, rate, n = (w.getnchannels(), w.getsampwidth(),
                          w.getframerate(), w.getnframes())
    if width != 2:
        raise SystemExit("%s: 16-bit PCM wanted" % path)
    s = struct.unpack("<%dh" % (n * ch), w.readframes(n))
    return [s[i * ch] for i in range(n)], rate


def resample(x, rate):
    """Linear interpolation to RATE."""
    if rate == RATE:
        return list(x)
    out = []
    n = int(len(x) * RATE / rate)
    for i in range(n):
        t = i * rate / RATE
        k = int(t)
        f = t - k
        b = x[k + 1] if k + 1 < len(x) else x[k]
        out.append(x[k] * (1 - f) + b * f)
    return out


def trim(x):
    a, b = 0, len(x)
    while a < b and abs(x[a]) < SILENCE:
        a += 1
    while b > a and abs(x[b - 1]) < SILENCE:
        b -= 1
    return x[a:b]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("dir", help="folder with the WAV files")
    ap.add_argument("-o", "--out", default=os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "..", "openrtx",
        "src", "protocols", "TETRA", "TetraTones.c"))
    args = ap.parse_args()

    body = []
    names = []
    for name, file in TONES:
        x, rate = read(os.path.join(args.dir, file))
        x = trim(resample(x, rate))
        peak = max(abs(v) for v in x) or 1
        y = [int(round(v * PEAK / peak)) for v in x]
        names.append(name)
        body.append("/* %s: %d ms */\n" % (file, len(y) * 1000 // RATE))
        body.append("static const int16_t %s[%d] = {\n" % (name, len(y)))
        for i in range(0, len(y), 10):
            body.append("    " + ", ".join("%d" % v for v in y[i:i + 10])
                        + ",\n")
        body.append("};\n\n")

    with open(args.out, "w") as f:
        f.write("/*\n * SPDX-FileCopyrightText: Copyright 2020-2026 OpenRTX "
                "Contributors\n *\n * SPDX-License-Identifier: "
                "GPL-3.0-or-later\n */\n\n")
        f.write("/* Generated by scripts/c62/tetra_tones.py: do not edit */\n\n")
        f.write("#include \"protocols/TETRA/TetraTones.h\"\n\n")
        f.writelines(body)
        f.write("const struct tetraToneSound tetraToneSounds[TETRA_TONE_NUM]"
                " = {\n")
        for n in names:
            f.write("    { %s, sizeof(%s) / sizeof(%s[0]) },\n" % (n, n, n))
        f.write("};\n")
    print("wrote", os.path.normpath(args.out))


if __name__ == "__main__":
    main()
